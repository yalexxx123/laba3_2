from random import uniform

# параметры мишени
R = 5.0
N = 10  # количество выстрелов

print(f"Мишень: радиус R={R}, выстрелов: {N}")
print(" " * 12 + "X" + " " * 15 + "Y" + " " * 5 + "Результат")
print("-" * 45)

# цикл для 10 выстрелов
for i in range(1, N + 1):
    # координаты точки в диапазоне от -R до R
    x = uniform(-R, R)
    y = uniform(-R, R)
    
    flag = False 
    
    # проверка попадания в 1-ю часть (четверть круга)
    # условия: x >= 0, y >= 0 и x^2 + y^2 <= R^2
    if (x >= 0 and y >= 0 and x**2 + y**2 <= R**2):
        flag = True
        
    # проверка попадания во 2-ю часть (прямоугольник)
    # условия: 0 <= x <= R и -R <= y <= 0
    elif (0 <= x <= R and -R <= y <= 0):
        flag = True
        
    # результат
    res = "Yes (Попадание)" if flag else "No  (Промах)"
    print(f"Выстрел {i:2d}: X = {x:6.2f}  Y = {y:6.2f}   ->   {res}")

print("-" * 45)